def first_url(j):
    m = re.search(r"https?://\S+", j or "")
    return m.group(0).rstrip(";,、。") if m else ""


def h_text(mark, I, J):
    """元のH列と同じ「記号 根拠 URL」の形に組み直す。"""
    body = re.sub(r"^[○△×]\s*", "", (I or "").strip())
    body = re.sub(r"\s+", " ", body)
    u = first_url(J)
    return ("%s %s %s" % (mark, body, u)).strip()


def write(path, header, rows):
    with open(path, "w", encoding="utf-8-sig", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(header)
        w.writerows(rows)
    print("  %-46s %5d行" % (os.path.basename(path), len(rows)))


